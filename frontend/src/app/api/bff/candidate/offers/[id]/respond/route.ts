import { NextRequest, NextResponse } from "next/server";
import { getSessionFromCookie, verifyCsrfOrigin } from "@/lib/server/session";

const backendInternalUrl = (process.env.BACKEND_INTERNAL_URL || "http://127.0.0.1:8000").replace(/\/+$/, "");

export async function POST(
  request: NextRequest,
  { params }: { params: Promise<{ id: string }> }
) {
  try {
    if (!verifyCsrfOrigin(request)) {
      return NextResponse.json({ error: "CSRF_ORIGIN_MISMATCH" }, { status: 403 });
    }

    const { id } = await params;
    if (!id || typeof id !== "string") {
      return NextResponse.json({ error: "INVALID_OFFER_ID" }, { status: 400 });
    }

    const session = await getSessionFromCookie();
    if (!session || !session.access_token) {
      return NextResponse.json(
        { error: "AUTH_REQUIRED", message: "Taklifga javob berish uchun tizimga kirish talab etiladi." },
        { status: 401 }
      );
    }

    const body = await request.json().catch(() => ({}));
    const decision = body.decision || body.response;
    if (!decision || !["ACCEPT", "DECLINE"].includes(String(decision).toUpperCase())) {
      return NextResponse.json(
        { error: "VALIDATION_ERROR", message: "Faqat 'ACCEPT' yoki 'DECLINE' qabul qilinadi." },
        { status: 422 }
      );
    }

    // Backend OfferRespondRequest has extra='forbid'
    const backendPayload: Record<string, unknown> = {
      decision: String(decision).toUpperCase(),
    };
    if (body.note && typeof body.note === "string") {
      backendPayload.note = body.note.trim();
    }

    const res = await fetch(`${backendInternalUrl}/api/v1/offers/${encodeURIComponent(id)}/respond`, {
      method: "POST",
      headers: {
        "Authorization": `Bearer ${session.access_token}`,
        "Content-Type": "application/json",
        "Accept": "application/json",
      },
      body: JSON.stringify(backendPayload),
      cache: "no-store",
    });

    const data = await res.json().catch(() => null);

    if (!res.ok) {
      return NextResponse.json(
        data || { error: "OFFER_RESPONSE_FAILED" },
        { status: res.status }
      );
    }

    return NextResponse.json(data, { status: res.status });
  } catch (err: unknown) {
    const message = err instanceof Error ? err.message : "Internal Server Error";
    return NextResponse.json({ error: message }, { status: 500 });
  }
}
